'use strict';
const { Pool, types } = require('pg');

// Keep DATE as 'YYYY-MM-DD' strings and NUMERIC as exact strings.
types.setTypeParser(1082, (v) => v);
types.setTypeParser(1700, (v) => v);
types.setTypeParser(20, (v) => Number(v));

const SCHEMA = `
create table if not exists users (
  id             bigint generated by default as identity primary key,
  email_hash     bytea  not null unique,
  email_enc      text   not null,
  first_name_enc text   not null,
  password_hash  text   not null,
  webauthn_id    bytea  not null,
  created_at     timestamptz not null default now()
);
create table if not exists sessions (
  id_hash    bytea primary key,
  user_id    bigint not null references users(id) on delete cascade,
  created_at timestamptz not null default now(),
  last_seen  timestamptz not null default now(),
  expires_at timestamptz not null
);
create index if not exists sessions_user on sessions(user_id);
create table if not exists login_attempts (
  key          bytea primary key,
  failures     int not null,
  window_start timestamptz not null
);
create table if not exists entries (
  id             bigint generated by default as identity primary key,
  user_id        bigint not null references users(id) on delete cascade,
  entry_date     date   not null,
  initials_enc   text   not null,
  start_enc      text   not null,
  end_enc        text   not null,
  program_enc    text   not null,
  odometer_start numeric(12,1) not null,
  odometer_end   numeric(12,1) not null,
  created_at     timestamptz not null default now()
);
create index if not exists entries_user_date on entries(user_id, entry_date);
create table if not exists remembered (
  user_id    bigint not null references users(id) on delete cascade,
  kind       text   not null,
  value_hash bytea  not null,
  value_enc  text   not null,
  primary key (user_id, kind, value_hash)
);
create table if not exists templates (
  user_id       bigint primary key references users(id) on delete cascade,
  file_name_enc text  not null,
  content_enc   bytea not null,
  uploaded_at   timestamptz not null default now()
);
create table if not exists rates (
  user_id        bigint not null references users(id) on delete cascade,
  effective_date date   not null,
  rate           numeric(7,4) not null,
  primary key (user_id, effective_date)
);
create table if not exists credentials (
  id         text primary key,
  user_id    bigint not null references users(id) on delete cascade,
  public_key bytea  not null,
  counter    bigint not null,
  transports text   not null default '',
  label_enc  text   not null,
  created_at timestamptz not null default now(),
  last_used  timestamptz
);
create index if not exists credentials_user on credentials(user_id);
create table if not exists challenges (
  id_hash    bytea primary key,
  challenge  text not null,
  user_id    bigint references users(id) on delete cascade,
  purpose    text not null,
  expires_at timestamptz not null
);
`;

/** Vercel's Neon integration may name the variable with a prefix (e.g. STORAGE_DATABASE_URL). */
function databaseUrl() {
  const env = process.env;
  if (env.DATABASE_URL) return env.DATABASE_URL;
  if (env.POSTGRES_URL) return env.POSTGRES_URL;
  const key = Object.keys(env).sort().find((k) => /(^|_)(DATABASE_URL|POSTGRES_URL)$/.test(k) && /^postgres(ql)?:\/\//.test(env[k]));
  if (key) return env[key];
  if (env.PGHOST && env.PGUSER && env.PGDATABASE) {
    const u = new URL('postgresql://' + env.PGHOST);
    u.username = env.PGUSER;
    u.password = env.PGPASSWORD || '';
    u.pathname = '/' + env.PGDATABASE;
    return u.toString();
  }
  return null;
}

function connectionConfig() {
  const url = databaseUrl();
  if (!url) {
    throw Object.assign(new Error('the database isn\'t connected. In Vercel: Storage → Create Database → Neon, connect it to this project, then redeploy.'), { setup: true });
  }
  const u = new URL(url);
  const local = ['localhost', '127.0.0.1', '::1'].includes(u.hostname) || u.hostname.startsWith('/');
  u.searchParams.delete('sslmode');
  u.searchParams.delete('channel_binding');
  return {
    connectionString: u.toString(),
    // Remote databases: TLS with full certificate verification.
    ssl: local ? false : { rejectUnauthorized: true },
    max: 3,
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 10_000,
  };
}

let pool;
let ready;
function getPool() {
  if (!pool) {
    pool = new Pool(connectionConfig());
    pool.on('error', () => {}); // idle client errors are recovered on next query
  }
  return pool;
}

async function migrate() {
  const client = await getPool().connect();
  try {
    await client.query('begin');
    await client.query('select pg_advisory_xact_lock(727274)');
    await client.query(SCHEMA);
    await client.query('commit');
  } catch (e) {
    await client.query('rollback').catch(() => {});
    throw e;
  } finally {
    client.release();
  }
}

async function query(text, params) {
  if (!ready) ready = migrate().catch((e) => { ready = null; throw e; });
  await ready;
  return getPool().query(text, params);
}

async function tx(fn) {
  if (!ready) ready = migrate().catch((e) => { ready = null; throw e; });
  await ready;
  const client = await getPool().connect();
  try {
    await client.query('begin');
    const out = await fn(client);
    await client.query('commit');
    return out;
  } catch (e) {
    await client.query('rollback').catch(() => {});
    throw e;
  } finally {
    client.release();
  }
}

async function end() {
  if (pool) await pool.end();
  pool = null;
  ready = null;
}

module.exports = { query, tx, end };
